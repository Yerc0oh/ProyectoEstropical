-- ---------------------------------------------------------------------
-- [FUNCION + TRIGGER 1/1]  CONTROL DE CUPOS Y ASIENTOS             (CU-16, CU-18)
-- Evita la sobreventa: cuando una reserva pasa a estado "activo"
-- (pendiente/confirmada) descuenta cupos del paquete y asientos de los
-- vuelos del paquete; cuando se cancela, expira o cambia el numero de
-- pasajeros, devuelve o ajusta la diferencia.
-- Si no hay cupo, el CHECK de paquete/vuelo hace fallar la operacion.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_ajustar_cupos() RETURNS TRIGGER AS $$
DECLARE
    v_antes   INTEGER := 0;
    v_despues INTEGER := 0;
    v_delta   INTEGER;
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.estado IN ('pendiente','confirmada') THEN
        v_antes := OLD.cantidad_pasajeros;
    END IF;
    IF NEW.estado IN ('pendiente','confirmada') THEN
        v_despues := NEW.cantidad_pasajeros;
    END IF;

    v_delta := v_despues - v_antes;          -- >0 ocupa cupos, <0 libera
    IF v_delta <> 0 THEN
        UPDATE paquete
           SET cupos_disponibles = cupos_disponibles - v_delta
         WHERE id = NEW.paquete_id;

        UPDATE vuelo
           SET asientos_disponibles = asientos_disponibles - v_delta
         WHERE id IN (SELECT vuelo_id FROM paquete_vuelo WHERE paquete_id = NEW.paquete_id);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reserva_cupos
AFTER INSERT OR UPDATE OF estado, cantidad_pasajeros ON reserva
FOR EACH ROW EXECUTE FUNCTION fn_ajustar_cupos();


-- ---------------------------------------------------------------------
-- [FUNCION]  CALCULO DE PENALIDAD Y REEMBOLSO                         (CU-21)
-- Segun los dias que faltan para la salida, toma el % de
-- parametro_sistema. Devuelve: % aplicado, penalidad (Bs) y monto
-- reembolsable (Bs) sobre lo efectivamente pagado.
-- Uso: SELECT * FROM fn_penalidad_cancelacion(15);
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_penalidad_cancelacion(p_reserva_id BIGINT)
RETURNS TABLE (porcentaje NUMERIC, penalidad NUMERIC, reembolsable NUMERIC) AS $$
DECLARE
    v_dias    INTEGER;
    v_total   NUMERIC;
    v_pagado  NUMERIC;
    v_pct     NUMERIC;
BEGIN
    SELECT (p.fecha_salida - CURRENT_DATE), r.total
      INTO v_dias, v_total
      FROM reserva r JOIN paquete p ON p.id = r.paquete_id
     WHERE r.id = p_reserva_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reserva % no existe', p_reserva_id;
    END IF;

    SELECT COALESCE(SUM(monto), 0) INTO v_pagado
      FROM pago WHERE reserva_id = p_reserva_id AND estado = 'completado';

    SELECT valor::NUMERIC INTO v_pct FROM parametro_sistema
     WHERE clave = CASE
                     WHEN v_dias >= 30 THEN 'penalidad_30_dias_o_mas'
                     WHEN v_dias >= 15 THEN 'penalidad_15_a_29_dias'
                     WHEN v_dias >= 7  THEN 'penalidad_7_a_14_dias'
                     ELSE 'penalidad_menos_7_dias'
                   END;

    porcentaje   := v_pct;
    penalidad    := LEAST(v_pagado, ROUND(v_total * v_pct / 100, 2));
    reembolsable := v_pagado - penalidad;
    RETURN NEXT;
END;
$$ LANGUAGE plpgsql STABLE;


-- ---------------------------------------------------------------------
-- [FUNCION]  CIERRE DE CAJA DEL DIA                                   (CU-37)
-- Consolida en un cierre: ingresos = pagos completados del dia;
-- egresos = reembolsos procesados + pagos a proveedores del dia.
-- Marca cada operacion con cierre_caja_id para que no se cierre dos veces.
-- Devuelve el id del cierre. Uso: SELECT fn_cerrar_caja(CURRENT_DATE, 3);
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cerrar_caja(p_fecha DATE, p_perfil_id BIGINT)
RETURNS BIGINT AS $$
DECLARE
    v_ingresos NUMERIC(12,2);
    v_egresos  NUMERIC(12,2);
    v_cierre   BIGINT;
    v_tz CONSTANT TEXT := 'America/La_Paz';
BEGIN
    SELECT COALESCE(SUM(monto), 0) INTO v_ingresos
      FROM pago
     WHERE estado = 'completado' AND cierre_caja_id IS NULL
       AND (fecha_pago AT TIME ZONE v_tz)::DATE = p_fecha;

    SELECT COALESCE((SELECT SUM(monto_reembolso) FROM reembolso
                      WHERE estado = 'procesado' AND cierre_caja_id IS NULL
                        AND (fecha_procesado AT TIME ZONE v_tz)::DATE = p_fecha), 0)
         + COALESCE((SELECT SUM(monto) FROM pago_proveedor
                      WHERE estado = 'pagado' AND cierre_caja_id IS NULL
                        AND (fecha_pago AT TIME ZONE v_tz)::DATE = p_fecha), 0)
      INTO v_egresos;

    INSERT INTO cierre_caja (fecha, total_ingresos, total_egresos, realizado_por_id)
    VALUES (p_fecha, v_ingresos, v_egresos, p_perfil_id)
    RETURNING id INTO v_cierre;           -- falla si ya hay cierre de esa fecha (UNIQUE)

    UPDATE pago SET cierre_caja_id = v_cierre
     WHERE estado = 'completado' AND cierre_caja_id IS NULL
       AND (fecha_pago AT TIME ZONE v_tz)::DATE = p_fecha;
    UPDATE reembolso SET cierre_caja_id = v_cierre
     WHERE estado = 'procesado' AND cierre_caja_id IS NULL
       AND (fecha_procesado AT TIME ZONE v_tz)::DATE = p_fecha;
    UPDATE pago_proveedor SET cierre_caja_id = v_cierre
     WHERE estado = 'pagado' AND cierre_caja_id IS NULL
       AND (fecha_pago AT TIME ZONE v_tz)::DATE = p_fecha;

    RETURN v_cierre;
END;
$$ LANGUAGE plpgsql;


-- ---------------------------------------------------------------------
-- [VISTA 1/2]  SALDO POR RESERVA                            (CU-29, CU-35)
-- Estado de cuenta del cliente y cuentas por cobrar de la agencia.
-- No existe tabla "cuenta_por_cobrar": el saldo se deriva de
-- reserva.total, pagos completados y reembolsos procesados.
-- Cuentas por cobrar = WHERE saldo_pendiente > 0.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_saldo_reserva AS
SELECT r.id AS reserva_id,
       r.codigo,
       r.cliente_id,
       r.estado,
       r.total,
       COALESCE(pg.pagado, 0)     AS pagado,
       COALESCE(rb.reembolsado, 0) AS reembolsado,
       CASE WHEN r.estado IN ('cancelada','expirada') THEN 0
            ELSE r.total - COALESCE(pg.pagado, 0) END AS saldo_pendiente,
       COALESCE(cu.vencidas, 0)   AS cuotas_vencidas
  FROM reserva r
  LEFT JOIN (SELECT reserva_id, SUM(monto) AS pagado
               FROM pago WHERE estado = 'completado' GROUP BY reserva_id) pg
         ON pg.reserva_id = r.id
  LEFT JOIN (SELECT reserva_id, SUM(monto_reembolso) AS reembolsado
               FROM reembolso WHERE estado = 'procesado' GROUP BY reserva_id) rb
         ON rb.reserva_id = r.id
  LEFT JOIN (SELECT reserva_id, COUNT(*) AS vencidas
               FROM cuota WHERE estado = 'pendiente' AND fecha_vencimiento < CURRENT_DATE
              GROUP BY reserva_id) cu
         ON cu.reserva_id = r.id;


-- ---------------------------------------------------------------------
-- [VISTA 2/2]  REPORTE DE VENTAS POR MES Y PAQUETE     (CU-40, CU-41, CU-43)
-- Base de reportes y panel de indicadores. Cuenta solo reservas que
-- generan venta (confirmadas o completadas).
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_reporte_ventas AS
SELECT date_trunc('month', r.fecha_reserva)::DATE AS mes,
       p.id          AS paquete_id,
       p.nombre      AS paquete,
       d.nombre      AS destino,
       COUNT(*)                    AS reservas,
       SUM(r.cantidad_pasajeros)   AS pasajeros,
       SUM(r.total)                AS total_vendido
  FROM reserva r
  JOIN paquete p ON p.id = r.paquete_id
  JOIN destino d ON d.id = p.destino_id
 WHERE r.estado IN ('confirmada','completada')
 GROUP BY 1, p.id, p.nombre, d.nombre;
