-- =====================================================================
--  ESTROPICAL.COM - Tropical Tours Ltda.
--  Esquema de base de datos (PostgreSQL 14+)
--  Cubre los 52 casos de uso del backlog (6 sprints).
--
--  CONVENCIONES
--   * Nombres en español, snake_case, tablas en singular.
--   * PK: BIGINT IDENTITY (igual que BigAutoField de Django).
--   * Montos en bolivianos: NUMERIC(12,2).
--   * Estados: VARCHAR + CHECK (no se crean tablas para listas fijas).
--   * Borrado lógico (activo / estado) en catálogos que tienen historial.
--
--  SEÑALIZACION DE OBJETOS PROGRAMADOS (todo lo que no es tabla)
--   [FUNCION]  fn_penalidad_cancelacion, fn_cerrar_caja, fn_ajustar_cupos
--   [TRIGGER]  trg_reserva_cupos
--   [VISTA]    v_saldo_reserva, v_reporte_ventas
--
--  UNICO PUNTO DE CONTACTO CON DJANGO
--   perfil.usuario_id guarda el id del usuario de autenticacion.
--   Correo, contrasena, roles (grupos), bloqueo de cuenta, sesiones,
--   bitacora y errores viven SOLO en Django admin. No se crea FK aqui:
--   Django la declara con OneToOneField(settings.AUTH_USER_MODEL).
-- =====================================================================


-- =====================================================================
-- 1. GEOGRAFIA Y DESTINOS                              (Sprint 1: CU-07, CU-08)
-- =====================================================================
CREATE TABLE pais (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_iso  CHAR(2)     NOT NULL UNIQUE,
    nombre      VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE categoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50) NOT NULL UNIQUE,          -- Playa, Aventura, Cultural...
    descripcion VARCHAR(200)
);

CREATE TABLE destino (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais_id       BIGINT       NOT NULL REFERENCES pais(id),
    categoria_id  BIGINT       NOT NULL REFERENCES categoria(id),
    nombre        VARCHAR(100) NOT NULL,
    codigo_iata   CHAR(3)      UNIQUE,                -- solo si tiene aeropuerto
    descripcion   TEXT,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE, -- "eliminar" = desactivar
    UNIQUE (pais_id, nombre)
);

CREATE TABLE destino_foto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destino_id  BIGINT       NOT NULL REFERENCES destino(id) ON DELETE CASCADE,
    archivo     VARCHAR(255) NOT NULL,                -- ruta (ImageField)
    descripcion VARCHAR(200),
    orden       SMALLINT     NOT NULL DEFAULT 0,
    es_portada  BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_destino_foto_portada ON destino_foto(destino_id) WHERE es_portada;


-- =====================================================================
-- 2. PERFIL DE PERSONA                      (Sprint 1: CU-05, CU-23; Sprint 5: CU-38)
--    Una fila por usuario de Django. Sirve para clientes y empleados;
--    el rol lo define el grupo de Django, no esta tabla.
-- =====================================================================
CREATE TABLE perfil (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT       NOT NULL UNIQUE,     -- id del usuario Django (sin FK)
    nombres          VARCHAR(80)  NOT NULL,
    apellidos        VARCHAR(80)  NOT NULL,
    tipo_documento   VARCHAR(10)  NOT NULL DEFAULT 'CI'
                     CHECK (tipo_documento IN ('CI','PASAPORTE','CE')),
    nro_documento    VARCHAR(20)  NOT NULL,
    fecha_nacimiento DATE,
    telefono         VARCHAR(20),
    direccion        VARCHAR(200),
    nacionalidad_id  BIGINT       REFERENCES pais(id),
    nit              VARCHAR(20),                      -- datos fiscales por defecto
    razon_social     VARCHAR(150),
    fecha_registro   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (tipo_documento, nro_documento)
);

-- Preferencias de viaje (CU-38): categorias de interes del usuario
CREATE TABLE perfil_categoria (
    perfil_id    BIGINT NOT NULL REFERENCES perfil(id)    ON DELETE CASCADE,
    categoria_id BIGINT NOT NULL REFERENCES categoria(id) ON DELETE CASCADE,
    PRIMARY KEY (perfil_id, categoria_id)
);

-- Destinos favoritos (CU-49)
CREATE TABLE favorito (
    perfil_id       BIGINT      NOT NULL REFERENCES perfil(id)  ON DELETE CASCADE,
    destino_id      BIGINT      NOT NULL REFERENCES destino(id) ON DELETE CASCADE,
    fecha_agregado  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (perfil_id, destino_id)
);


-- =====================================================================
-- 3. PROVEEDORES, HOTELES Y VUELOS                (Sprint 2: CU-13 a CU-16)
-- =====================================================================
CREATE TABLE proveedor (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social      VARCHAR(150) NOT NULL,
    nit               VARCHAR(20)  NOT NULL UNIQUE,
    tipo              VARCHAR(15)  NOT NULL
                      CHECK (tipo IN ('aerolinea','hotel','operador','transporte','otro')),
    nombre_contacto   VARCHAR(100),
    correo            VARCHAR(120),
    telefono          VARCHAR(20),
    estado_validacion VARCHAR(10)  NOT NULL DEFAULT 'pendiente'
                      CHECK (estado_validacion IN ('pendiente','validado','rechazado')),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE proveedor_documento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id      BIGINT       NOT NULL REFERENCES proveedor(id) ON DELETE CASCADE,
    tipo_documento    VARCHAR(50)  NOT NULL,           -- NIT, licencia, contrato...
    archivo           VARCHAR(255) NOT NULL,
    fecha_vencimiento DATE,
    estado            VARCHAR(10)  NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','aprobado','rechazado')),
    observacion       VARCHAR(250),
    revisado_por_id   BIGINT       REFERENCES perfil(id),
    fecha_carga       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_revision    TIMESTAMPTZ
);

CREATE TABLE hotel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id BIGINT       NOT NULL REFERENCES proveedor(id),
    destino_id   BIGINT       NOT NULL REFERENCES destino(id),
    nombre       VARCHAR(120) NOT NULL,
    estrellas    SMALLINT     NOT NULL CHECK (estrellas BETWEEN 1 AND 5),
    direccion    VARCHAR(200),
    descripcion  TEXT,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE tipo_habitacion (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id                  BIGINT       NOT NULL REFERENCES hotel(id) ON DELETE CASCADE,
    nombre                    VARCHAR(60)  NOT NULL,   -- Simple, Doble, Suite...
    capacidad                 SMALLINT     NOT NULL CHECK (capacidad > 0),
    habitaciones_total        INTEGER      NOT NULL CHECK (habitaciones_total >= 0),
    habitaciones_disponibles  INTEGER      NOT NULL,
    descripcion               VARCHAR(250),
    UNIQUE (hotel_id, nombre),
    CHECK (habitaciones_disponibles BETWEEN 0 AND habitaciones_total)
);

CREATE TABLE tarifa_habitacion (                       -- tarifa por temporada
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_habitacion_id  BIGINT        NOT NULL REFERENCES tipo_habitacion(id) ON DELETE CASCADE,
    fecha_inicio        DATE          NOT NULL,
    fecha_fin           DATE          NOT NULL,
    precio_noche        NUMERIC(10,2) NOT NULL CHECK (precio_noche > 0),
    UNIQUE (tipo_habitacion_id, fecha_inicio),
    CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE vuelo (                                   -- un vuelo = una salida concreta
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id          BIGINT        NOT NULL REFERENCES proveedor(id),  -- aerolinea
    numero_vuelo          VARCHAR(10)   NOT NULL,
    origen_id             BIGINT        NOT NULL REFERENCES destino(id),
    destino_id            BIGINT        NOT NULL REFERENCES destino(id),
    fecha_salida          TIMESTAMPTZ   NOT NULL,
    fecha_llegada         TIMESTAMPTZ   NOT NULL,
    asientos_total        INTEGER       NOT NULL CHECK (asientos_total > 0),
    asientos_disponibles  INTEGER       NOT NULL,
    precio_referencial    NUMERIC(10,2) NOT NULL CHECK (precio_referencial >= 0),
    estado                VARCHAR(12)   NOT NULL DEFAULT 'programado'
                          CHECK (estado IN ('programado','retrasado','cancelado','completado')),
    UNIQUE (numero_vuelo, fecha_salida),
    CHECK (origen_id <> destino_id),
    CHECK (fecha_llegada > fecha_salida),
    CHECK (asientos_disponibles BETWEEN 0 AND asientos_total)
);


-- =====================================================================
-- 4. PAQUETES TURISTICOS                          (Sprint 2: CU-09 a CU-12)
--    Convencion: cada paquete representa UNA salida con fechas concretas.
--    Una nueva fecha de salida = nuevo paquete (se puede duplicar).
-- =====================================================================
CREATE TABLE paquete (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destino_id         BIGINT        NOT NULL REFERENCES destino(id),
    nombre             VARCHAR(150)  NOT NULL,
    descripcion        TEXT,
    condiciones        TEXT,                              -- condiciones y politicas (CU-11)
    fecha_salida       DATE          NOT NULL,
    fecha_retorno      DATE          NOT NULL,            -- duracion = retorno - salida
    precio_persona     NUMERIC(12,2) NOT NULL CHECK (precio_persona > 0),
    cupos_total        INTEGER       NOT NULL CHECK (cupos_total > 0),
    cupos_disponibles  INTEGER       NOT NULL,
    venta_desde        DATE          NOT NULL,            -- vigencia de venta
    venta_hasta        DATE          NOT NULL,
    estado             VARCHAR(10)   NOT NULL DEFAULT 'borrador'
                       CHECK (estado IN ('borrador','publicado','archivado')),
    CHECK (fecha_retorno >= fecha_salida),
    CHECK (venta_hasta >= venta_desde AND venta_hasta <= fecha_salida),
    CHECK (cupos_disponibles BETWEEN 0 AND cupos_total)
);

CREATE TABLE paquete_hotel (
    paquete_id          BIGINT   NOT NULL REFERENCES paquete(id) ON DELETE CASCADE,
    tipo_habitacion_id  BIGINT   NOT NULL REFERENCES tipo_habitacion(id),
    noches              SMALLINT NOT NULL CHECK (noches > 0),
    PRIMARY KEY (paquete_id, tipo_habitacion_id)
);

CREATE TABLE paquete_vuelo (
    paquete_id  BIGINT      NOT NULL REFERENCES paquete(id) ON DELETE CASCADE,
    vuelo_id    BIGINT      NOT NULL REFERENCES vuelo(id),
    tramo       VARCHAR(10) NOT NULL DEFAULT 'ida' CHECK (tramo IN ('ida','vuelta','interno')),
    PRIMARY KEY (paquete_id, vuelo_id)
);

CREATE TABLE servicio (                                -- catalogo: traslado, desayuno, guia...
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

CREATE TABLE paquete_servicio (                        -- base de la comparacion (CU-10)
    paquete_id  BIGINT NOT NULL REFERENCES paquete(id)  ON DELETE CASCADE,
    servicio_id BIGINT NOT NULL REFERENCES servicio(id),
    detalle     VARCHAR(200),
    PRIMARY KEY (paquete_id, servicio_id)
);

CREATE TABLE paquete_actividad (                       -- cronograma base del itinerario (CU-25)
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paquete_id   BIGINT       NOT NULL REFERENCES paquete(id) ON DELETE CASCADE,
    dia          SMALLINT     NOT NULL CHECK (dia >= 1),
    orden        SMALLINT     NOT NULL DEFAULT 1,
    hora_inicio  TIME,
    titulo       VARCHAR(120) NOT NULL,
    descripcion  VARCHAR(300),
    UNIQUE (paquete_id, dia, orden)
);


-- =====================================================================
-- 5. PROMOCIONES Y CUPONES                                 (Sprint 6: CU-50)
-- =====================================================================
CREATE TABLE promocion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(30)   NOT NULL UNIQUE,
    descripcion    VARCHAR(200),
    tipo_descuento VARCHAR(10)   NOT NULL CHECK (tipo_descuento IN ('porcentaje','monto_fijo')),
    valor          NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    monto_minimo   NUMERIC(12,2) NOT NULL DEFAULT 0,
    vigente_desde  DATE          NOT NULL,
    vigente_hasta  DATE          NOT NULL,
    usos_maximos   INTEGER       CHECK (usos_maximos > 0),   -- NULL = ilimitado
    paquete_id     BIGINT        REFERENCES paquete(id),     -- NULL = aplica a todos
    activo         BOOLEAN       NOT NULL DEFAULT TRUE,
    CHECK (vigente_hasta >= vigente_desde),
    CHECK (tipo_descuento <> 'porcentaje' OR valor <= 100)
    -- usos realizados = COUNT(reserva WHERE promocion_id = id); no se guarda (derivable)
);


-- =====================================================================
-- 6. RESERVAS                                          (Sprint 3: CU-18 a CU-25)
-- =====================================================================
CREATE TABLE reserva (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)   NOT NULL UNIQUE,
    cliente_id          BIGINT        NOT NULL REFERENCES perfil(id),
    creada_por_id       BIGINT        NOT NULL REFERENCES perfil(id), -- cliente o empleado (CU-18)
    paquete_id          BIGINT        NOT NULL REFERENCES paquete(id),
    promocion_id        BIGINT        REFERENCES promocion(id),
    cantidad_pasajeros  SMALLINT      NOT NULL CHECK (cantidad_pasajeros > 0),
    precio_unitario     NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0), -- copia del precio al reservar
    descuento           NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (descuento >= 0),
    subtotal            NUMERIC(12,2) GENERATED ALWAYS AS (precio_unitario * cantidad_pasajeros) STORED,
    total               NUMERIC(12,2) GENERATED ALWAYS AS (precio_unitario * cantidad_pasajeros - descuento) STORED,
    estado              VARCHAR(10)   NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente','confirmada','cancelada','completada','expirada')),
    fecha_reserva       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_expiracion    TIMESTAMPTZ,                       -- limite para pagar
    confirmada_por_id   BIGINT        REFERENCES perfil(id),
    fecha_confirmacion  TIMESTAMPTZ,
    fecha_cancelacion   TIMESTAMPTZ,
    motivo_cancelacion  VARCHAR(250),
    observaciones       VARCHAR(300),
    CHECK (descuento <= precio_unitario * cantidad_pasajeros),
    CHECK ((estado = 'cancelada') = (fecha_cancelacion IS NOT NULL))
);

CREATE TABLE pasajero (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id       BIGINT      NOT NULL REFERENCES reserva(id) ON DELETE CASCADE,
    nombres          VARCHAR(80) NOT NULL,
    apellidos        VARCHAR(80) NOT NULL,
    tipo_documento   VARCHAR(10) NOT NULL CHECK (tipo_documento IN ('CI','PASAPORTE','CE')),
    nro_documento    VARCHAR(20) NOT NULL,
    fecha_nacimiento DATE        NOT NULL,
    nacionalidad_id  BIGINT      REFERENCES pais(id),
    UNIQUE (reserva_id, tipo_documento, nro_documento)
);

CREATE TABLE documento_viaje (                         -- archivos cargados (CU-24)
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pasajero_id       BIGINT       NOT NULL REFERENCES pasajero(id) ON DELETE CASCADE,
    tipo              VARCHAR(25)  NOT NULL
                      CHECK (tipo IN ('pasaporte','visa','ci','vacunacion','otro')),
    numero            VARCHAR(40),
    fecha_vencimiento DATE,
    archivo           VARCHAR(255) NOT NULL,
    fecha_carga       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE confirmacion_proveedor (                  -- CU-17
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id          BIGINT       NOT NULL REFERENCES reserva(id),
    proveedor_id        BIGINT       NOT NULL REFERENCES proveedor(id),
    concepto            VARCHAR(200) NOT NULL,         -- que servicio se solicita
    estado              VARCHAR(10)  NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente','confirmada','rechazada')),
    codigo_confirmacion VARCHAR(50),
    gestionado_por_id   BIGINT       REFERENCES perfil(id),
    fecha_solicitud     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_respuesta     TIMESTAMPTZ,
    observacion         VARCHAR(250),
    UNIQUE (reserva_id, proveedor_id, concepto)
);


-- =====================================================================
-- 7. PAGOS, FACTURACION Y CAJA                         (Sprint 4: CU-26 a CU-37)
-- =====================================================================
CREATE TABLE cierre_caja (                             -- CU-37
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE          NOT NULL UNIQUE,
    total_ingresos  NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_egresos   NUMERIC(12,2) NOT NULL DEFAULT 0,
    saldo           NUMERIC(12,2) GENERATED ALWAYS AS (total_ingresos - total_egresos) STORED,
    realizado_por_id BIGINT       NOT NULL REFERENCES perfil(id),
    fecha_cierre    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    observaciones   VARCHAR(250)
);

CREATE TABLE cuota (                                   -- plan de pagos fraccionados (CU-27)
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id        BIGINT        NOT NULL REFERENCES reserva(id),
    numero            SMALLINT      NOT NULL CHECK (numero > 0),
    monto             NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    fecha_vencimiento DATE          NOT NULL,
    estado            VARCHAR(10)   NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','pagada','anulada')),
    -- "vencida" no se guarda: es pendiente con fecha_vencimiento < hoy (ver v_saldo_reserva)
    UNIQUE (reserva_id, numero)
);

CREATE TABLE pago (                                    -- CU-26, CU-28, CU-34
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id             BIGINT        NOT NULL REFERENCES reserva(id),
    cuota_id               BIGINT        REFERENCES cuota(id),         -- NULL = pago unico
    metodo                 VARCHAR(15)   NOT NULL
                           CHECK (metodo IN ('qr','tarjeta','efectivo','transferencia')),
    canal                  VARCHAR(10)   NOT NULL CHECK (canal IN ('en_linea','ventanilla')),
    monto                  NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    estado                 VARCHAR(12)   NOT NULL DEFAULT 'pendiente'
                           CHECK (estado IN ('pendiente','completado','fallido','reembolsado')),
    fecha_pago             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    referencia_transaccion VARCHAR(100)  UNIQUE,       -- id de pasarela / nro de deposito
    nro_comprobante        VARCHAR(20)   UNIQUE,
    registrado_por_id      BIGINT        REFERENCES perfil(id),        -- cajero (ventanilla)
    conciliado             BOOLEAN       NOT NULL DEFAULT FALSE,       -- CU-34
    fecha_conciliacion     DATE,
    conciliado_por_id      BIGINT        REFERENCES perfil(id),
    cierre_caja_id         BIGINT        REFERENCES cierre_caja(id),
    CHECK (canal <> 'ventanilla' OR registrado_por_id IS NOT NULL),
    CHECK (conciliado = (fecha_conciliacion IS NOT NULL))
);

CREATE TABLE reembolso (                               -- CU-21, CU-33
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id        BIGINT        NOT NULL REFERENCES reserva(id),
    pago_id           BIGINT        NOT NULL REFERENCES pago(id),
    penalidad         NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (penalidad >= 0),
    monto_reembolso   NUMERIC(12,2) NOT NULL CHECK (monto_reembolso >= 0),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','procesado','rechazado')),
    metodo            VARCHAR(15)   CHECK (metodo IN ('qr','tarjeta','efectivo','transferencia')),
    referencia        VARCHAR(100),
    fecha_solicitud   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_procesado   TIMESTAMPTZ,
    procesado_por_id  BIGINT        REFERENCES perfil(id),
    cierre_caja_id    BIGINT        REFERENCES cierre_caja(id)
);

CREATE TABLE factura (                                 -- CU-30, CU-31, CU-32
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_factura        BIGINT        NOT NULL UNIQUE,
    reserva_id         BIGINT        NOT NULL REFERENCES reserva(id),
    nit_cliente        VARCHAR(20)   NOT NULL,         -- copia de los datos fiscales al emitir
    razon_social       VARCHAR(150)  NOT NULL,
    concepto           VARCHAR(250)  NOT NULL,
    monto              NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    estado             VARCHAR(10)   NOT NULL DEFAULT 'emitida'
                       CHECK (estado IN ('emitida','anulada')),
    archivo_pdf        VARCHAR(255),
    fecha_emision      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    emitida_por_id     BIGINT        NOT NULL REFERENCES perfil(id),
    fecha_anulacion    TIMESTAMPTZ,
    anulada_por_id     BIGINT        REFERENCES perfil(id),
    motivo_anulacion   VARCHAR(250),
    CHECK ((estado = 'anulada') = (fecha_anulacion IS NOT NULL))
);

CREATE TABLE pago_proveedor (                          -- CU-36
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id      BIGINT        NOT NULL REFERENCES proveedor(id),
    confirmacion_id   BIGINT        REFERENCES confirmacion_proveedor(id),
    monto             NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    metodo            VARCHAR(15)   NOT NULL CHECK (metodo IN ('transferencia','efectivo','cheque')),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','pagado')),
    fecha_pago        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    referencia        VARCHAR(100),
    registrado_por_id BIGINT        NOT NULL REFERENCES perfil(id),
    cierre_caja_id    BIGINT        REFERENCES cierre_caja(id),
    observacion       VARCHAR(250)
);


