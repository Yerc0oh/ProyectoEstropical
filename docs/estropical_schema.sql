-- 8. SOPORTE, RESENAS, NOTIFICACIONES Y CONFIGURACION     (Sprint 5 y 6)
-- =====================================================================
CREATE TABLE consulta_soporte (                        -- CU-45, CU-46
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT       NOT NULL REFERENCES perfil(id),
    reserva_id       BIGINT       REFERENCES reserva(id),      -- opcional
    asunto           VARCHAR(150) NOT NULL,
    mensaje          TEXT         NOT NULL,
    estado           VARCHAR(12)  NOT NULL DEFAULT 'abierta'
                     CHECK (estado IN ('abierta','en_proceso','respondida','cerrada')),
    fecha_consulta   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atendido_por_id  BIGINT       REFERENCES perfil(id),
    respuesta        TEXT,
    fecha_respuesta  TIMESTAMPTZ
);

CREATE TABLE resena (                                  -- CU-47, CU-48
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id        BIGINT      NOT NULL UNIQUE REFERENCES reserva(id), -- 1 resena por reserva
    calificacion      SMALLINT    NOT NULL CHECK (calificacion BETWEEN 1 AND 5),
    comentario        VARCHAR(500),
    estado            VARCHAR(10) NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente','aprobada','rechazada')),
    fecha             TIMESTAMPTZ NOT NULL DEFAULT now(),
    moderada_por_id   BIGINT      REFERENCES perfil(id),
    fecha_moderacion  TIMESTAMPTZ
    -- cliente y paquete se obtienen por reserva_id (sin redundancia)
);

CREATE TABLE notificacion (                            -- CU-44
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id    BIGINT       NOT NULL REFERENCES perfil(id) ON DELETE CASCADE,
    tipo         VARCHAR(15)  NOT NULL
                 CHECK (tipo IN ('reserva','pago','recordatorio','promocion','soporte','sistema')),
    canal        VARCHAR(10)  NOT NULL DEFAULT 'sistema' CHECK (canal IN ('sistema','correo')),
    titulo       VARCHAR(120) NOT NULL,
    mensaje      VARCHAR(400) NOT NULL,
    leida        BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_envio  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE parametro_sistema (                       -- CU-52
    clave        VARCHAR(60)  PRIMARY KEY,
    valor        VARCHAR(200) NOT NULL,
    descripcion  VARCHAR(200)
);

